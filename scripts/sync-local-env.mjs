import { existsSync, mkdirSync, renameSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const sourcePath = resolve(root, '.env.local');

const webKeys = [
  'NEXT_PUBLIC_API_URL',
  'NEXT_PUBLIC_TELEGRAM_API_ID',
  'NEXT_PUBLIC_TELEGRAM_API_HASH',
  'NEXT_PUBLIC_TELEGRAM_CHANNEL',
];
const workerKeys = [
  'APP_ORIGIN',
  'RP_ID',
  'RP_NAME',
  'BOOTSTRAP_TOKEN',
  'APP_SESSION_SECRET',
  'TELEGRAM_WEBHOOK_SECRET',
];
const allKeys = [...webKeys, ...workerKeys];

class EnvSyncError extends Error {}

function fail(message) {
  throw new EnvSyncError(message);
}

function quote(value) {
  return JSON.stringify(value);
}

function render(keys, values, target) {
  const header = [
    '# GENERATED by `pnpm env:sync`; do not edit.',
    `# Edit root .env.local, then rerun env:sync. Target: ${target}`,
    '',
  ];
  return `${header.join('\n')}${keys.map((key) => `${key}=${quote(values[key])}`).join('\n')}\n`;
}

function writeAtomic(path, contents) {
  mkdirSync(dirname(path), { recursive: true });
  const temporaryPath = `${path}.tmp`;
  writeFileSync(temporaryPath, contents, { encoding: 'utf8', mode: 0o600 });
  renameSync(temporaryPath, path);
}

function main() {
  if (!existsSync(sourcePath)) fail('root .env.local is missing; copy .env.example to .env.local first');
  if (typeof process.loadEnvFile !== 'function') fail('Node 20.6+ with process.loadEnvFile is required');

  // Root .env.local is sole source. Do not silently use inherited values.
  for (const key of allKeys) delete process.env[key];
  try {
    process.loadEnvFile(sourcePath);
  } catch {
    fail('could not parse root .env.local; check dotenv syntax');
  }

  const values = Object.fromEntries(allKeys.map((key) => [key, process.env[key] ?? '']));
  const missing = allKeys.filter((key) => values[key].trim() === '');
  if (missing.length > 0) fail(`missing non-empty values in root .env.local: ${missing.join(', ')}`);

  writeAtomic(resolve(root, 'apps/web/.env.local'), render(webKeys, values, 'apps/web/.env.local'));
  writeAtomic(resolve(root, 'apps/worker/.dev.vars'), render(workerKeys, values, 'apps/worker/.dev.vars'));
}

try {
  main();
} catch (error) {
  console.error(error instanceof EnvSyncError ? `env:sync failed: ${error.message}` : 'env:sync failed');
  process.exitCode = 1;
}
